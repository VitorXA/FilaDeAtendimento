CREATE TABLE IF NOT EXISTS users (
  id SERIAL PRIMARY KEY,
  username VARCHAR(50) UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  cpf VARCHAR(14) UNIQUE NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'PROVIDER',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS queues (
  id SERIAL PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  code VARCHAR(20) UNIQUE NOT NULL,
  provider_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  next_number INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS tickets (
  id SERIAL PRIMARY KEY,
  queue_id INTEGER NOT NULL REFERENCES queues(id) ON DELETE CASCADE,
  client_name VARCHAR(120) NOT NULL,
  number INTEGER NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'WAITING' CHECK (status IN ('WAITING','CALLED','SERVING','COMPLETED','SKIPPED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  called_at TIMESTAMPTZ,
  finished_at TIMESTAMPTZ,
  UNIQUE(queue_id, number)
);
CREATE INDEX IF NOT EXISTS idx_tickets_queue_status ON tickets(queue_id,status,number);
CREATE TABLE IF NOT EXISTS attendances (
  id SERIAL PRIMARY KEY,
  ticket_id INTEGER UNIQUE NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  provider_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  finished_at TIMESTAMPTZ
);
